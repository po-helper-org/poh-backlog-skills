"""Форматирование текста сообщений для правил: русское согласование числительных.

Модуль намеренно не знает ничего про модель беклога или правила — только
про то, как согласовать существительное с числом по-русски. И `hygiene.py`,
и `phases.py` могут использовать его без риска циклического импорта.
"""
from __future__ import annotations


def ru_plural(count: int, one: str, few: str, many: str) -> str:
    """Возвращает форму существительного, согласованную с `count`.

    `one` — форма для чисел, оканчивающихся на 1 (кроме 11): 1, 21, 31…
    `few` — форма для чисел, оканчивающихся на 2-4 (кроме 12-14): 2, 3, 4, 22…
    `many` — форма для всех остальных: 0, 5-20, 25-30 и т. д.

    Пример: ru_plural(1, "слово", "слова", "слов") -> "слово".
    """
    remainder_100 = count % 100
    if 11 <= remainder_100 <= 14:
        return many
    remainder_10 = count % 10
    if remainder_10 == 1:
        return one
    if 2 <= remainder_10 <= 4:
        return few
    return many
